- resource：资源链接（工具官网、GitHub 仓库、产品页、在线演示、官方文档、下载页、插件页等）
- auxiliary：辅助链接（参考资料、引用文章、相关项目、补充阅读）
- pending：无法判断用途或真实指向
只能使用清单中已有的 ID，不要新增链接。无关的导航、登录、分享类链接可以不列出。

