    /** 已知的历代内置默认提示词（不含当前版本）。 */
    val LEGACY_DEFAULTS: List<String> get() = listOf(LEGACY_1_0_0)

    private fun canon(s: String) = s.replace("\r\n", "\n").trim()

    /** 是否为某个旧版内置默认提示词（即用户从未自定义过）。 */
    fun isLegacyDefault(prompt: String): Boolean = LEGACY_DEFAULTS.any { canon(it) == canon(prompt) }

    /**
     * 升级迁移：用户当前提示词仍是旧版默认（未自定义）时，返回新默认；已自定义或已是新默认则返回 null（不动）。
     */
    fun migrationTarget(currentPrompt: String, storedRevision: Int): String? {
        if (storedRevision >= REVISION) return null
        if (canon(currentPrompt) == canon(TEXT)) return null
        return if (isLegacyDefault(currentPrompt)) TEXT else null
    }
