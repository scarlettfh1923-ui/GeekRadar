- 结构清晰：开头一句抓住注意力，中间用短段落或 ✅ 小条目列出要点，结尾给出上手方式或提醒。emoji 适度（全文 3–8 个）。
- 正文里不要写话题标签（#…），标签单独放在 tags 字段。
- 需要提到链接时，只写链接编号，例如「项目地址见 [L2]」；不要写出任何 URL。
- 给出 3 个风格不同的标题候选，每个不超过 20 个汉字。
- 给出 3–6 个小红书话题标签，不带 # 号，每个不超过 10 个字，例如 AI工具、开源项目、效率神器。

